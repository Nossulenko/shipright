#!/usr/bin/env node
/**
 * Generates the runtime adapters for every role in .agents/roles/.
 *
 *   .agents/roles/<name>.md  ──►  .claude/agents/<name>.md        (Claude Code subagent)
 *                            ──►  .github/agents/<name>.agent.md  (GitHub Copilot custom agent)
 *                            ──►  .codex/agents/<name>.toml       (Codex role)
 *                            ──►  .codex/config.toml              (Codex role declarations)
 *
 * The role file is the single source of truth. Adapters embed its body, so each
 * runtime gets the full instructions without an extra file read.
 *
 * Usage:
 *   node scripts/sync-agents.mjs           write adapters
 *   node scripts/sync-agents.mjs --check   exit 1 if any adapter is out of date
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseFrontmatter } from "./lib/frontmatter.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ROLES_DIR = join(ROOT, ".agents/roles");
const MARKER = "GENERATED by scripts/sync-agents.mjs";

const CLAUDE_MODELS = new Set(["opus", "sonnet", "haiku", "inherit"]);
const CODEX_SANDBOXES = new Set(["read-only", "workspace-write"]);

export function loadRoles() {
  if (!existsSync(ROLES_DIR)) return [];
  return readdirSync(ROLES_DIR)
    .filter((f) => f.endsWith(".md"))
    .sort()
    .map((file) => {
      const source = `.agents/roles/${file}`;
      const { data, body } = parseFrontmatter(readFileSync(join(ROLES_DIR, file), "utf8"));
      return { file, source, data: data ?? {}, body: body.trim() };
    });
}

export function validateRole(role) {
  const errors = [];
  const d = role.data;
  const expected = role.file.replace(/\.md$/, "");
  if (!d.name) errors.push("missing `name`");
  else if (d.name !== expected) errors.push(`name "${d.name}" must equal file name "${expected}"`);
  if (!d.description || String(d.description).length < 20) errors.push("missing or too-short `description`");
  if (d["claude-model"] && !CLAUDE_MODELS.has(d["claude-model"]))
    errors.push(`claude-model must be one of ${[...CLAUDE_MODELS].join(", ")}`);
  if (!CODEX_SANDBOXES.has(d["codex-sandbox"]))
    errors.push(`codex-sandbox must be one of ${[...CODEX_SANDBOXES].join(", ")}`);
  if (d["copilot-tools"] !== undefined && !Array.isArray(d["copilot-tools"]))
    errors.push("copilot-tools must be an inline array, e.g. [read, search]");
  if (d["codex-sandbox"] === "read-only") {
    const claudeTools = String(d["claude-tools"] ?? "");
    if (!claudeTools) errors.push("read-only roles must declare an explicit claude-tools list");
    if (/\b(Write|Edit|MultiEdit|Bash|NotebookEdit)\b/.test(claudeTools))
      errors.push("read-only role lists an editing or shell tool in claude-tools");
    const copilot = d["copilot-tools"] ?? [];
    if (copilot.some((t) => ["edit", "execute", "shell"].includes(t)))
      errors.push("read-only role lists edit/execute in copilot-tools");
  }
  if (!role.body) errors.push("empty body");
  return errors;
}

function header(source, comment) {
  return `${comment} ${MARKER} from ${source} — edit that file, then run \`npm run sync:agents\`.`;
}

function claudeAdapter(role) {
  const d = role.data;
  const lines = ["---", `name: ${d.name}`, `description: ${JSON.stringify(d.description)}`];
  if (d["claude-model"]) lines.push(`model: ${d["claude-model"]}`);
  if (d["claude-tools"]) lines.push(`tools: ${d["claude-tools"]}`);
  lines.push("---", "", `<!-- ${header(role.source, "").trim()} -->`, "", role.body, "");
  return lines.join("\n");
}

function copilotAdapter(role) {
  const d = role.data;
  const lines = ["---", `name: ${d.name}`, `description: ${JSON.stringify(d.description)}`];
  if (d["copilot-tools"]) lines.push(`tools: ${JSON.stringify(d["copilot-tools"])}`);
  lines.push("---", "", `<!-- ${header(role.source, "").trim()} -->`, "", role.body, "");
  return lines.join("\n");
}

function tomlMultiline(text) {
  if (!text.includes("'''")) return `'''\n${text}\n'''`;
  const escaped = text.replace(/\\/g, "\\\\").replace(/"""/g, '""\\"');
  return `"""\n${escaped}\n"""`;
}

function codexAdapter(role) {
  const d = role.data;
  return [
    header(role.source, "#"),
    `name = ${JSON.stringify(d.name)}`,
    `description = ${JSON.stringify(d.description)}`,
    `sandbox_mode = ${JSON.stringify(d["codex-sandbox"])}`,
    `developer_instructions = ${tomlMultiline(role.body)}`,
    "",
  ].join("\n");
}

function codexConfig(roles) {
  const lines = [
    header(".agents/roles/*", "#"),
    "# Codex project config: hooks, MCP servers, and role declarations.",
    "# A file in .codex/agents/ is inert until it is declared here.",
    "",
    "[features]",
    "hooks = true",
    "",
    "[mcp_servers.playwright]",
    'command = "npx"',
    'args = ["-y", "@playwright/mcp@latest"]',
    "required = false",
    "",
    "[mcp_servers.shadcn]",
    'command = "npx"',
    'args = ["-y", "shadcn@latest", "mcp"]',
    "required = false",
    "",
  ];
  for (const role of roles) {
    lines.push(`[agents.${role.data.name}]`, `config_file = "agents/${role.data.name}.toml"`, "");
  }
  return lines.join("\n");
}

/** Every file the generator owns, mapped to its expected content. */
export function buildAll(roles = loadRoles()) {
  const files = new Map();
  for (const role of roles) {
    const name = role.data.name;
    files.set(`.claude/agents/${name}.md`, claudeAdapter(role));
    files.set(`.github/agents/${name}.agent.md`, copilotAdapter(role));
    files.set(`.codex/agents/${name}.toml`, codexAdapter(role));
  }
  files.set(".codex/config.toml", codexConfig(roles));
  return files;
}

/** Generated files on disk that no longer have a role behind them. */
export function staleFiles(expected) {
  const stale = [];
  for (const dir of [".claude/agents", ".github/agents", ".codex/agents"]) {
    const abs = join(ROOT, dir);
    if (!existsSync(abs)) continue;
    for (const f of readdirSync(abs)) {
      const rel = `${dir}/${f}`;
      if (expected.has(rel)) continue;
      if (readFileSync(join(abs, f), "utf8").includes(MARKER)) stale.push(rel);
    }
  }
  return stale;
}

export function diffAgainstDisk(expected = buildAll()) {
  const outOfDate = [];
  for (const [rel, content] of expected) {
    const abs = join(ROOT, rel);
    if (!existsSync(abs) || readFileSync(abs, "utf8") !== content) outOfDate.push(rel);
  }
  return { outOfDate, stale: staleFiles(expected) };
}

function main() {
  const check = process.argv.includes("--check");
  const roles = loadRoles();

  const invalid = roles.flatMap((r) => validateRole(r).map((e) => `${r.source}: ${e}`));
  if (invalid.length) {
    console.error(invalid.map((e) => `✗ ${e}`).join("\n"));
    process.exit(1);
  }

  const expected = buildAll(roles);
  const { outOfDate, stale } = diffAgainstDisk(expected);

  if (check) {
    if (!outOfDate.length && !stale.length) {
      console.log(`✓ ${roles.length} roles, adapters in sync`);
      return;
    }
    for (const f of outOfDate) console.error(`✗ out of date: ${f}`);
    for (const f of stale) console.error(`✗ stale (role removed): ${f}`);
    console.error("Run `npm run sync:agents` and commit the result.");
    process.exit(1);
  }

  for (const rel of outOfDate) {
    const abs = join(ROOT, rel);
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, expected.get(rel));
    console.log(`  wrote ${rel}`);
  }
  for (const rel of stale) {
    rmSync(join(ROOT, rel));
    console.log(`  removed ${rel}`);
  }
  console.log(`✓ ${roles.length} roles synced to Claude Code, Codex and Copilot`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
